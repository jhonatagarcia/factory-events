CREATE TABLE events (
                        event_id VARCHAR(100) NOT NULL,
                        event_type VARCHAR(20) NOT NULL,
                        description VARCHAR(2000) NOT NULL,
                        occurred_at TIMESTAMPTZ NOT NULL,
                        received_at TIMESTAMPTZ NOT NULL,

                        CONSTRAINT pk_events
                            PRIMARY KEY (event_id),

                        CONSTRAINT ck_events_type
                            CHECK (event_type IN ('PRODUCTION', 'QUALITY')),

                        CONSTRAINT ck_events_description
                            CHECK (length(btrim(description)) > 0)
);

CREATE TABLE event_audits (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY,
                              event_id VARCHAR(100) NOT NULL,
                              action VARCHAR(50) NOT NULL,
                              created_at TIMESTAMPTZ NOT NULL,

                              CONSTRAINT pk_event_audits
                                  PRIMARY KEY (id),

                              CONSTRAINT fk_event_audits_event
                                  FOREIGN KEY (event_id)
                                      REFERENCES events (event_id),

                              CONSTRAINT uk_event_audits_event
                                  UNIQUE (event_id),

                              CONSTRAINT ck_event_audits_action
                                  CHECK (action = 'QUALITY_EVENT_REGISTERED')
    );

CREATE INDEX idx_events_received_at_event_id
    ON events (received_at DESC, event_id ASC);